let lang = "en";
try {
  lang =
    localStorage.getItem("relaynest-language") ||
    navigator.language.split("-")[0];
} catch {}
i18n
  .use(initReactI18next)
  .init({
    resources: Object.fromEntries(
      Object.entries({ en, ...translated }).map(([k, v]) => [
        k,
        { translation: v },
      ]),
    ),
    lng: languages[lang] ? lang : "en",
    fallbackLng: "en",
    interpolation: { escapeValue: false },
  });
i18n.on("languageChanged", (lng) => {
  localStorage.setItem("relaynest-language", lng);
  document.documentElement.lang = lng;
  document.documentElement.dir = lng === "ar" ? "rtl" : "ltr";
});
if (typeof document !== "undefined") {
  document.documentElement.lang = i18n.resolvedLanguage || "en";
  document.documentElement.dir = i18n.resolvedLanguage === "ar" ? "rtl" : "ltr";
}
export default i18n;
